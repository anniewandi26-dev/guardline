import { writeFileSync, readdirSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { pathToFileURL, fileURLToPath } from "node:url";
import { languages, DEFAULT_LANG } from "./i18n/languages.mjs";
import { countryToLang } from "./i18n/country-map.mjs";
import { en } from "./i18n/_keys.mjs";

const __dirname = dirname(fileURLToPath(import.meta.url));
const packsDir = join(__dirname, "i18n", "packs");

const uiStrings = { en: { ...en } };

const packName = (code) => `${code}.mjs`;

for (const { code } of languages) {
  if (code === "en") continue;
  const file = join(packsDir, packName(code));
  if (!existsSync(file)) {
    uiStrings[code] = { ...en };
    console.warn(`missing pack ${code} — using English fallback`);
    continue;
  }
  const mod = await import(pathToFileURL(file).href);
  const pack = mod.default || mod;
  uiStrings[code] = { ...en, ...pack };
}

const keyRef = Object.keys(en).sort();
let mismatches = 0;
for (const { code } of languages) {
  const keys = Object.keys(uiStrings[code] || {});
  const absent = keyRef.filter((k) => !(k in uiStrings[code]));
  if (absent.length) {
    mismatches += 1;
    console.warn(`${code} missing ${absent.length} keys e.g. ${absent[0]}`);
  }
  if (keys.length < keyRef.length) {
    uiStrings[code] = { ...en, ...uiStrings[code] };
  }
}

const payload = {
  defaultLang: DEFAULT_LANG,
  languages,
  countryToLang,
  strings: uiStrings,
};

const out = `/* Auto-generated by build-i18n.mjs — do not edit by hand */\nwindow.SHOUHAO_I18N = ${JSON.stringify(payload)};\n`;
writeFileSync(join(__dirname, "locales.js"), out);

// Also write assembled ui-strings for tooling
const assembled = `import { en } from "./_keys.mjs";\n\nexport const uiStrings = ${JSON.stringify(uiStrings, null, 2)};\n`;
writeFileSync(join(__dirname, "i18n", "ui-strings.mjs"), assembled);

console.log(
  `Built locales.js: ${languages.length} languages, ${keyRef.length} keys, mismatches=${mismatches}`
);
